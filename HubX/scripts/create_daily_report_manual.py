from pathlib import Path

from docx import Document
from docx.oxml.ns import qn


OUTPUT_PATH = Path(__file__).resolve().parents[1] / "docs" / "日报填写操作手册（简版）.docx"


def add_lines(document: Document, lines: list[str]) -> None:
    for line in lines:
        document.add_paragraph(line)


def main() -> None:
    document = Document()
    normal_style = document.styles["Normal"]
    normal_style.font.name = "PingFang SC"
    normal_style._element.rPr.rFonts.set(qn("w:eastAsia"), "PingFang SC")

    add_lines(
        document,
        [
            "日报填写操作手册（简版）",
            "",
            "一、填写顺序",
            "每条日报对应一项实际工作，请按以下顺序填写：工作归属、关联项目、工作性质、工作内容、用时。",
            "当天涉及不同项目或不同工作性质时，请分别新增多条记录，不要合并填写。",
            "",
            "二、工作归属说明",
            "开发：适用于软件项目交付、维护及技术支持，例如功能开发、测试、部署、需求分析。",
            "软件售前：适用于软件类客户线索、方案、报价及商务推进，例如线索跟进、客户沟通、方案撰写、报价沟通。",
            "移民售前：适用于移民业务客户咨询与售前服务，例如客户咨询、方案制定、材料收集、案件推进。",
            "运营：适用于公司内部经营与职能事务，例如招聘、人事管理、财务管理、行政办公、OA 流程优化。",
            "电商：适用于电商平台、店铺及商品运营工作，例如商品上架、活动策划、客服协同、售后处理。",
            "推广：适用于品牌、内容、广告及流量运营工作，例如广告投放、内容发布、SEO 优化、数据分析。",
            "",
            "三、工作性质说明",
            "工作性质用于说明这段时间具体做了什么，系统会根据员工所属部门和岗位加载可选项。",
            "请选择最贴近实际工作的工作性质，不要只选择岗位名称。",
            "开发人员可选择：需求分析、原型设计、功能开发、接口开发、Bug 修复、测试、部署发布等。",
            "软件售前可选择：线索跟进、客户拜访、方案撰写、报价沟通、合同推进、催款等。",
            "运营人员可选择：招聘面试、薪酬核算、报销审核、发票管理、会议组织、采购管理等。",
            "电商人员可选择：商品优化、平台运营、活动策划、客户咨询、订单跟进、售后处理等。",
            "推广人员可选择：广告投放、素材测试、内容发布、SEO 优化、数据分析、效果复盘等。",
            "",
            "四、关联项目选择",
            "请选择与本条工作直接相关的项目。",
            "软件售前可选择对应项目；线索跟进类工作可选择“线索跟进工时汇总”。",
            "运营、移民售前、电商、推广等工作归属下的项目选项，由日报项目配置维护，系统会根据工作归属显示对应项目。",
            "没有合适项目或工作性质时，请先选择最接近项，在工作内容中写明实际事项，并反馈负责人补充配置。",
            "",
            "五、工作内容与用时",
            "工作内容应简要写清产出或进展，例如：完成客户小程序需求方案初稿并沟通修改意见。",
            "用时填写实际投入时长，建议按 0.5 小时为单位。",
            "不建议只填写“处理工作”“沟通项目”等笼统描述。",
        ],
    )

    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    document.save(OUTPUT_PATH)
    print(OUTPUT_PATH)


if __name__ == "__main__":
    main()
